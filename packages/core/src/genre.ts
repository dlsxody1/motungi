/**
 * 장르 어휘 통합 (표시·검색용 순수 함수).
 *
 * `genre`(0017)는 소스 원문을 그대로 보존한다 — 통합 enum을 두지 않은 건 원문을 잃지
 * 않기 위한 옳은 결정이었다. 다만 그 대가로 **같은 개념이 소스마다 다른 이름**으로 남는다
 * (실측 2026-09-03):
 *
 *   전시/미술 55(seoul_culture) vs 전시 44(culture_info)
 *   콘서트 17                   vs 음악/콘서트 17
 *   무용 10                     vs 무용/발레 1
 *
 * 그래서 "미술"로 검색하면 culture_info의 44건이 통째로 안 잡히고, 필터 UI를 만들면
 * "전시"가 두 번 나와 각각 절반씩 든다. 저장 스키마는 건드리지 않고 **읽는 쪽에서**
 * 통합 라벨을 붙인다(normalizeGu와 같은 성격 — 표시 로직이지 저장 스키마가 아니다).
 */

/** 원문 → 통합 라벨. 키는 소스가 실제로 주는 값(실측 기준). */
