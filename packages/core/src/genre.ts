  // 전시
  "전시/미술": "전시",
  전시: "전시",
  // 음악 — 클래식·국악·독주회는 사용자가 "음악"으로 묶어 찾는다.
  콘서트: "음악",
  "음악/콘서트": "음악",
  클래식: "음악",
  국악: "음악",
  "독주/독창회": "음악",
  // kopis는 같은 개념을 또 다른 이름으로 준다(실측 2026-09-03 서울 300건:
  // 서양음악(클래식) 99 · 대중음악 83 · 한국음악(국악) 21).
  "서양음악(클래식)": "음악",
  대중음악: "음악",
  "한국음악(국악)": "음악",
  // 무용
  무용: "무용",
  "무용/발레": "무용",
  "무용(서양/한국무용)": "무용",
  대중무용: "무용",
  // 축제 — seoul_culture가 "축제-<소분류>"로 잘게 쪼개 준다. 사용자에겐 다 축제다.
  "축제-문화/예술": "축제",
  "축제-기타": "축제",
  "축제-시민화합": "축제",
  "축제-관광/체육": "축제",
  "축제-전통/역사": "축제",
  "행사/축제": "축제",
  // 나머지는 두 소스가 같은 이름을 쓴다 — 멱등을 위해 자기 자신으로 명시.
  연극: "연극",
  "뮤지컬/오페라": "뮤지컬/오페라",
  // kopis는 오페라를 따로 세지 않고 "뮤지컬"만 준다 — 기존 라벨로 합친다.
  뮤지컬: "뮤지컬/오페라",
  "교육/체험": "교육/체험",
