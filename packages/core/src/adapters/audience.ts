/**
 * 관람 대상 게이트 — 아동 전용 프로그램을 큐레이션에서 제외한다.
 *
 * seoul-jobs의 isAfterWorkShift와 같은 성격의 **컨셉 게이트**다. "퇴근하고 뭐하지"는
 * 성인 직장인용이라 어린이 프로그램이 원픽에 오르면 안 된다. 실제로 "신정동 · 문화공연 ·
 * 주말 · 방전형" 진단의 원픽이 [마포구립서강도서관] 어린이 여름 독서교실(10~12시)이었다.
 *
 * ⚠️ 함정 1 — "이상"은 하한 표기다.
 * "8세 이상 관람 가능"·"초등학생 이상"은 **성인도 포함**한다. 아동 토큰만 보고 지우면
 * 정상 후보를 잘라낸다. 그래서 상한없음 표기가 있으면 통과시킨다.
 *
 * ⚠️ 함정 2 — 상한없음 표기는 USE_TRGT에만 적용한다. 제목엔 쓰면 안 된다.
 * 실측: 제목에 "이상"을 포함한 culture 8건이 전부 오탐이었다 — "이상원 개인전"(인명),
 * "상, 상 이상: 모란조각대상"(전시명). 제목의 "이상"은 대상 표기가 아니다.
 *
 * ⚠️ 함정 3 — 이 게이트는 culture 전용이다. 전역에 걸면 안 된다.
 * 실측: 제목에 아동 토큰을 가진 49건 중 **26건이 seoul_jobs의 "○○어린이집 · 보육 교사"**다.
 * 어린이집 구인은 성인이 지원하는 정상적인 부업 후보다. 호출부가 culture만 통과시킨다.
 */

/** 아동·청소년 대상 토큰. */
const KID_TOKEN = /어린이|유아|아동|초등|청소년|키즈|영유아|미취학|중학생|고등학생/;

/**
 * "그 나이 이상 누구나"를 뜻하는 표기 — 있으면 성인도 참여 가능하므로 제외하지 않는다.
 * USE_TRGT(이용 대상) 문자열에만 적용할 것(함정 2).
 */
const ALL_AGES = /이상|누구나|전체\s*관람|전연령|전\s*연령|제한\s*없|성인|무관/;

/**
 * 아동 전용이면 true(=제외 대상).
 *
 * @param useTarget 이용 대상 원문. seoul_culture의 USE_TRGT(실측 채움률 100%).
 * @param title 대상 정보가 없는 소스(culture_info)를 위한 폴백.
 *
 * 판단 근거가 아예 없으면 **false(통과)**. isAfterWorkShift는 미상을 제외하지만 여기선
 * 반대다 — audience는 재적재 전까지 전 행이 null이라, 미상을 제외하면 카탈로그가 통째로 빈다.
 */
export function isKidsOnly(useTarget?: string | null, title?: string | null): boolean {
  const target = useTarget?.trim();
  if (target) return KID_TOKEN.test(target) && !ALL_AGES.test(target);

  // USE_TRGT가 없는 소스는 제목으로만 판단한다. 상한없음 검사는 하지 않는다(함정 2).
  // 장소명 제외 목록은 두지 않는다 — "송파어린이문화회관"처럼 장소가 진짜 신호인 경우와
  // "서울어린이대공원 아트센터"처럼 아닌 경우가 섞여 규칙화되지 않는다.
  const name = title?.trim();
  return name ? KID_TOKEN.test(name) : false;
}
